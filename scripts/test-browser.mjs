import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const context = await browser.newContext({ httpCredentials: { username:'owner',password:process.env.ASSISTANT_PASSWORD }, viewport: { width:1440,height:1000 } });
const page = await context.newPage(); const errors = [];
page.on('pageerror',e => errors.push(e.message));
try {
  await page.goto(process.env.ASSISTANT_URL || 'http://127.0.0.1:3000');
  await page.getByText('Demo mode · no model called',{exact:false}).waitFor();
  await page.locator('.privacy-controls summary').click();
  await page.getByLabel('Memory relationship').fill('prefers');
  await page.getByLabel('Personal fact').fill('morning deep work');
  await page.getByRole('button',{name:'Save personal fact',exact:true}).click();
  await page.getByText('Fact saved locally.',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Daily Planner',exact:true}).click();
  await page.getByLabel('Task',{exact:true}).fill('Record the hackathon demo');
  await page.getByRole('button',{name:'Add task',exact:true}).click();
  await page.locator('.task-row').filter({hasText:'Record the hackathon demo'}).waitFor();
  await page.getByRole('button',{name:'Build local plan',exact:true}).click();
  await page.locator('.plan-timeline').getByText('Record the hackathon demo',{exact:true}).waitFor();
  await page.screenshot({path:'/tmp/sovereignclaw-planner.png',fullPage:true});
  await page.getByLabel('Complete Record the hackathon demo').click();
  await page.waitForFunction(() => document.querySelector('.task-row.done'));
  await page.getByRole('button',{name:/Reusable Skill Forge/}).click();
  await page.getByPlaceholder('Function name (e.g. sharpe_ratio_calc)').fill('browser_demo_skill');
  await page.getByPlaceholder('Description…').fill('A reusable browser demo check');
  await page.locator('.page-content textarea').fill("print('BROWSER_SKILL_WORKED')");
  await page.getByRole('button',{name:/Register Skill/}).click();
  await page.getByText(/Successfully executed.*BROWSER_SKILL_WORKED/).waitFor();
  await page.getByRole('button',{name:/Command Cockpit/}).click();
  await page.getByPlaceholder(/Ask SovereignClaw/).fill('Execute skill browser_demo_skill');
  await page.getByPlaceholder(/Ask SovereignClaw/).press('Enter');
  await page.locator('.chat-message.assistant').filter({hasText:'BROWSER_SKILL_WORKED'}).waitFor();
  await page.reload();
  await page.locator('.chat-message.assistant').filter({hasText:'BROWSER_SKILL_WORKED'}).waitFor();
  await page.locator('.privacy-controls summary').click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button',{name:'Export all personal data'}).click();
  const download = await downloadPromise; assert.ok(download.suggestedFilename().endsWith('.json'));
  await page.setViewportSize({width:390,height:844});
  await page.locator('.privacy-controls summary').click();
  await page.getByRole('button',{name:'Daily Planner',exact:true}).click();
  await page.getByLabel('Task',{exact:true}).fill('Mobile follow-up task');
  await page.getByRole('button',{name:'Add task',exact:true}).click();
  await page.locator('.task-row').filter({hasText:'Mobile follow-up task'}).waitFor();
  const width = await page.locator('.main-content').evaluate(el => el.getBoundingClientRect().width);
  assert.ok(width >= 380, 'Mobile content is squeezed by the sidebar');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile page overflows horizontally');
  await page.screenshot({path:'/tmp/sovereignclaw-mobile.png',fullPage:true});
  assert.deepEqual(errors,[],'browser runtime errors');
  console.log('PASS: browser privacy controls, task creation/planning/completion, skill registration, chat persistence, data export, mobile rendering');
} finally { await browser.close(); }
